public class ArithmeticOP {
    public static void main(String[] args)
    {
        //Arithmetic Operators used for mathematical calculation
        // first we declear two values to perform all this operators 
        int A = 10;
        int B = 5;
        
        // now we used all operators
        System.out.printf("Result = %d%n",A+B);//Addition of A + B
        System.out.printf("Result = %d%n",A-B);//Subtraction of A -B
        System.out.printf("Result = %d%n",A*B);//Multiplication of A * B
        System.out.printf("Result = %d%n",A/B);//Division of A / B
        System.out.printf("Result = %d%n",A%B);//Remainder of A % B
    }
    
}
