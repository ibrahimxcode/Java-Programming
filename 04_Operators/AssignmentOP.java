public class AssignmentOP {
        public static void main(String[] args)
    {
        //Assignment Operators used to asign or update values
        // first we declear two values to perform all this operators

        // now we used all operators
        int A = 10;// asing value to variable
        int B = 10;// asing value to variable
        System.out.println("Asing value of A =" +A);
        System.out.println("Asing value of B =" +B);

        A += 5;// updateing Value of variable's
        B -= 5;// updateing Value of Variables's
        System.out.println("Update Value of A =" +A);
        System.out.println("Update Value of B =" +B);

        A *= 5;// updateing Value of variable's
        B /= 5;// updateing Value of Variables's
        System.out.println("Update Value of A =" +A);
        System.out.println("Update Value of B =" +B);

        B %= 5;// updateing Value of Variables's
        System.out.println("Update Value of B =" +B);
    }
    
}
