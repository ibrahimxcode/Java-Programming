public class RelationComparisonOP {
    public static void main(String[] args)
    {
        //Realtion/Comparison Operators used to compare tow values the result is always true or false(
        // first we declear two values to perform all this operators 
        int A = 10;
        int B = 5;
        
        // now we used all operators
        System.out.println("A Equal to B = "+(A==B));// ==
        System.out.println("A Not Equal to B ="+(A!=B));// !=
        System.out.println("A greater then B ="+(A>B));// >
        System.out.println("A Less then B ="+(A<B));// <
        System.out.println("A Greater the equal to B ="+(A>=B)); // >=
        System.out.println("A Less the equal to B ="+(A<=B));// <=
    }
    
}
