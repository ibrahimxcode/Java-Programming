// class = defines a class
// Hello = name of the class
class Firstprogram{

    // main() = starting point of the Java program
    // public = accessible from anywhere
    // static = can run without creating an object
    // void = does not return any value
    // String[] args = stores command-line arguments
    public static void main(String[] args) {

        // System = Java's built-in class for system operations
        // out = represents the output screen
        // println() = prints the message and moves to a new line
        System.out.println("Hello World");

    } // End of main() method

} // End of Hello class
